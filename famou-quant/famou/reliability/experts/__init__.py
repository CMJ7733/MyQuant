def _render_hyperparams(hyperparams: Dict[str, Any]) -> str:
    """Render HYPERPARAMS as a PYTHON literal, one key per line.

    Not ``json.dumps``: JSON writes ``true``/``false``/``null``, which are
    NameErrors in Python. That only bites families with boolean or None
    hyperparameters (the NN families have ``layer_norm``), so a JSON-rendered
    template passes the GBDT tests and then fails every MLP candidate at
    import time.
    """
    lines = [f"    {key!r}: {value!r}," for key, value in hyperparams.items()]
    return "{\n" + "\n".join(lines) + "\n}"


def _render_template(family: str, expert: str, hyperparams: Dict[str, Any]) -> str:
    return CANDIDATE_TEMPLATE.format(
        family=family,
        expert=expert,
        hyperparams_json=_render_hyperparams(hyperparams),
    )


