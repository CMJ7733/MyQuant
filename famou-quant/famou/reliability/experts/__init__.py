def default_expert_registry(
    *,
    rng_seed: int = 0,
    families: Optional[Sequence[str]] = None,
    llm_edit_fn: Optional[Any] = None,
) -> Dict[str, ProposalExpert]:
    """Experts keyed by the lookup the strategy uses: ``family`` /
    ``family_explore`` / ``family_hpo``.

    ``families`` restricts the pool — pass ``TaskSpec.allowed_model_families``
    so the search space the experts can reach is exactly the one the frozen
    contract declares. Omit it to get every implemented family.
    """
    allowed = set(families) if families else None

    def wanted(family: str) -> bool:
        return allowed is None or family in allowed

    registry: Dict[str, ProposalExpert] = {}
    if wanted("gbdt"):
        registry.update({
            "gbdt": GBDTExpert(ExpertKind.MUTATE, rng_seed=rng_seed),
            "gbdt_explore": GBDTExpert(ExpertKind.EXPLORE, rng_seed=rng_seed + 1),
            "gbdt_hpo": GBDTExpert(ExpertKind.LOCAL_HPO, rng_seed=rng_seed + 2),
        })
    if wanted("mlp"):
        registry["mlp"] = NNExpert(ExpertKind.EXPLORE, rng_seed=rng_seed + 3,
                                   family="mlp", llm_edit_fn=llm_edit_fn)
    if wanted("temporal_transformer"):
        registry["temporal_transformer"] = NNExpert(
            ExpertKind.EXPLORE, rng_seed=rng_seed + 4,
            family="temporal_transformer", llm_edit_fn=llm_edit_fn)
    if wanted("formula"):
        registry.update({
            "formula": FormulaExpert(ExpertKind.MUTATE, rng_seed=rng_seed + 5,
                                     llm_edit_fn=llm_edit_fn),
            "formula_explore": FormulaExpert(ExpertKind.EXPLORE,
                                             rng_seed=rng_seed + 6),
            "formula_hpo": FormulaExpert(ExpertKind.LOCAL_HPO,
                                         rng_seed=rng_seed + 7),
        })

    if not registry:
        raise ValueError(
            f"no experts for families={sorted(allowed or [])}; "
            "implemented: gbdt, mlp, temporal_transformer, formula"
        )
    return registry
