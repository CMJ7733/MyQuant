# Formula expert (deterministic, no training)
# =============================================================================

#: Alpha158 factor families worth combining, grouped by what they measure.
#: Sampling across groups rather than uniformly over all 158 columns keeps a
#: formula from being five flavours of the same momentum signal — the diversity
#: that makes a multi-factor score worth more than its best single term.
FACTOR_GROUPS: Dict[str, List[str]] = {
    "momentum": ["ROC5", "ROC10", "ROC20", "ROC60", "MA5", "MA20", "MA60"],
    "reversal": ["RSV5", "RSV20", "RANK5", "RANK20", "QTLU20", "QTLD20"],
    "volatility": ["STD5", "STD20", "STD60", "MAX20", "MIN20", "BETA20"],
    "trend_quality": ["RSQR5", "RSQR20", "RSQR60", "RESI5", "RESI20"],
    "volume": ["VMA5", "VMA20", "VSTD20", "WVMA20", "VSUMP20", "VSUMD20"],
    "price_volume": ["CORR5", "CORR20", "CORD5", "CORD20"],
    "updown": ["CNTP20", "CNTN20", "CNTD20", "SUMP20", "SUMN20", "SUMD20"],
    "shape": ["KMID", "KLEN", "KUP", "KLOW", "KSFT"],
    "position": ["IMAX20", "IMIN20", "IMXD20"],
}

TRANSFORMS = ("zscore", "rank", "sign")


class FormulaExpert(ProposalExpert):
    """Proposes deterministic multi-factor scores over Alpha158.

    Why this family exists alongside the trained models: a formula costs
    ~0.06s to score against ~40-105s to train one. That two-orders-of-magnitude
    gap is what makes the budget machinery (per-candidate compute ceilings,
    cost penalties in the reward, the fidelity ladder) do real work — with only
    GBDT and MLP in the pool, every candidate costs roughly the same and those
    mechanisms are never exercised.

    It is also the interpretable end of the pool: the winning candidate is a
    weighted factor list you can print in a paper, not a boosted ensemble.
    """

    model_family = "formula"

    def __init__(
        self,
        kind: ExpertKind = ExpertKind.MUTATE,
        rng_seed: int = 0,
        *,
        min_terms: int = 3,
        max_terms: int = 8,
        llm_edit_fn: Optional[Any] = None,
    ):
        self.kind = kind
        self.min_terms = min_terms
        self.max_terms = max_terms
        self._llm_edit_fn = llm_edit_fn
        import random

        self._rng = random.Random(rng_seed)

    # -- spec ------------------------------------------------------------

    def build_spec(self, hyperparams: Dict[str, Any]) -> QuantModelSpec:
        terms = hyperparams.get("terms", [])
        return QuantModelSpec(
            model_family=self.model_family,
            # For a formula, the "feature pipeline" IS the model: which factors
            # and how they are normalised.
            feature_pipeline={
                "factors": [t.get("feature") for t in terms],
                "transforms": [t.get("transform") for t in terms],
            },
            architecture={"n_terms": len(terms), "kind": "linear_combination"},
            loss="none",
            optimizer={},
            training={"deterministic": True, "fitted_parameters": 0},
        )

    # -- proposal --------------------------------------------------------

    def propose(
        self,
        action: StructuredAction,
        parents: List[Program],
        *,
        iteration: int,
    ) -> Program:
        if self._llm_edit_fn is not None and parents:
            code = self._llm_edit_fn(parents[0].code, action)
            program = self._new_program(code, action=action, parents=parents,
                                        iteration=iteration)
            program.meta["llm_guided"] = True
            return program

        base: Optional[Dict[str, Any]] = None
        if parents and self.kind != ExpertKind.EXPLORE:
            try:
                base = self.extract_hyperparams(parents[0])
            except (ValueError, SyntaxError):
                base = None

        params = self._fresh() if base is None else self._mutate(base)
        code = _render_formula(self.kind.value, params)
        return self._new_program(code, action=action, parents=parents,
                                 iteration=iteration)

    # -- generation ------------------------------------------------------

    def _fresh(self) -> Dict[str, Any]:
        """Sample a new formula: one factor from each of K distinct groups."""
        rng = self._rng
        n = rng.randint(self.min_terms, self.max_terms)
        groups = rng.sample(list(FACTOR_GROUPS), min(n, len(FACTOR_GROUPS)))
        terms = []
        for group in groups:
            terms.append({
                "feature": rng.choice(FACTOR_GROUPS[group]),
                "weight": round(rng.uniform(-1.0, 1.0), 4),
                "transform": rng.choice(TRANSFORMS),
            })
        return {"terms": self._normalise(terms)}

    def _mutate(self, base: Dict[str, Any]) -> Dict[str, Any]:
        rng = self._rng
        terms = [dict(t) for t in base.get("terms", [])]
        if not terms:
            return self._fresh()

        op = rng.choice(["reweight", "swap", "add", "drop", "retransform"])
        if op == "reweight":
            # Perturb every weight; large edits to one term tend to just delete
            # it, which the `drop` op already covers.
            for t in terms:
                t["weight"] = round(float(t["weight"]) + rng.gauss(0, 0.25), 4)
        elif op == "swap" and terms:
            t = rng.choice(terms)
            group = self._group_of(t["feature"]) or rng.choice(list(FACTOR_GROUPS))
            t["feature"] = rng.choice(FACTOR_GROUPS[group])
        elif op == "add" and len(terms) < self.max_terms:
            used_groups = {self._group_of(t["feature"]) for t in terms}
            spare = [g for g in FACTOR_GROUPS if g not in used_groups]
            group = rng.choice(spare or list(FACTOR_GROUPS))
            terms.append({
                "feature": rng.choice(FACTOR_GROUPS[group]),
                "weight": round(rng.uniform(-0.6, 0.6), 4),
                "transform": rng.choice(TRANSFORMS),
            })
        elif op == "drop" and len(terms) > self.min_terms:
            terms.pop(rng.randrange(len(terms)))
        elif op == "retransform" and terms:
            rng.choice(terms)["transform"] = rng.choice(TRANSFORMS)
        return {"terms": self._normalise(terms)}

    # -- helpers ---------------------------------------------------------

    @staticmethod
    def _group_of(feature: str) -> Optional[str]:
        for group, members in FACTOR_GROUPS.items():
            if feature in members:
                return group
        return None

    @staticmethod
    def _normalise(terms: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Scale weights to unit L1, and drop terms that rounded to nothing.

        RankIC is invariant to a positive rescaling of the score, so the
        overall magnitude is not a real degree of freedom. Fixing it keeps
        mutation operating on the *relative* weights, and stops two identical
        formulas at different scales from looking like distinct candidates.
        """
        kept = [t for t in terms if abs(float(t.get("weight", 0.0))) >= 0.01]
        if not kept:
            kept = terms[:1] or [{"feature": "ROC20", "weight": 1.0,
                                  "transform": "zscore"}]
        total = sum(abs(float(t["weight"])) for t in kept) or 1.0
        for t in kept:
            t["weight"] = round(float(t["weight"]) / total, 4)
        return kept


def _render_formula(expert: str, hyperparams: Dict[str, Any]) -> str:
    return FORMULA_TEMPLATE.format(
        expert=expert,
        hyperparams_json=_render_hyperparams(hyperparams),
    )


