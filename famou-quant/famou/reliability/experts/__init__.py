class ProposalExpert:
    """Base class for action -> candidate translation."""

    kind: ExpertKind = ExpertKind.EXPLORE
    model_family: str = "unknown"

    def propose(
        self,
        action: StructuredAction,
        parents: List[Program],
        *,
        iteration: int,
    ) -> Program:
        raise NotImplementedError

    # -- packaging ------------------------------------------------------

    def build_spec(self, hyperparams: Dict[str, Any]) -> QuantModelSpec:
        """Structured view of the candidate.

        Subclasses split their hyperparameter dict into the four editable
        components so ``edit_target`` can name one and a diff can show which
        one actually moved.
        """
        return QuantModelSpec(
            model_family=self.model_family, architecture=dict(hyperparams)
        )

    def package(
        self,
        program: Program,
        *,
        episode_id: str,
        data_contract_hash: str = "",
        task_spec_hash: str = "",
    ) -> CandidatePackage:
        """Wrap a generated Program as a fully-stamped CandidatePackage.

        The two hashes travel with the candidate so a result can never be
        compared against a protocol it was not produced under.
        """
        try:
            hyperparams = self.extract_hyperparams(program)
        except (ValueError, SyntaxError):
            hyperparams = {}
        meta = program.meta or {}
        return CandidatePackage(
            candidate_id=program.id,
            episode_id=episode_id,
            code=program.code,
            code_hash=CandidatePackage.hash_code(program.code),
            spec=self.build_spec(hyperparams),
            parent_ids=list(meta.get("parent_ids", [])),
            decision_id=meta.get("decision_id"),
            expert=meta.get("expert", self.kind.value),
            data_contract_hash=data_contract_hash,
            task_spec_hash=task_spec_hash,
            generation_meta={
                "edit_target": meta.get("edit_target"),
                "fidelity": meta.get("fidelity"),
                "seed_list": meta.get("seed_list", []),
                "rationale": meta.get("rationale", ""),
                "llm_guided": bool(meta.get("llm_guided", False)),
            },
        )

    # -- helpers --------------------------------------------------------

    def _new_program(
        self,
        code: str,
        *,
        action: StructuredAction,
        parents: List[Program],
        iteration: int,
    ) -> Program:
        parent_id = parents[0].id if parents else None
        generation = (parents[0].generation + 1) if parents else 0
        return Program(
            id=f"cand_{iteration}_{uuid.uuid4().hex[:8]}",
            code=code,
            generation=generation,
            iteration=iteration,
            language=Language.PYTHON,
            parent_id=parent_id,
            created_at=get_timestamp(),
            meta={
                "expert": self.kind.value,
                "model_family": self.model_family,
                "edit_target": action.edit_target,
                "fidelity": int(action.fidelity.value),
                "seed_list": list(action.seed_list),
                "parent_ids": [p.id for p in parents],
                "rationale": action.rationale,
            },
        )

    @staticmethod
    def extract_hyperparams(program: Program) -> Dict[str, Any]:
        """Pull the HYPERPARAMS dict out of a candidate's source code."""
        import ast

        tree = ast.parse(program.code)
        for node in tree.body:
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id == "HYPERPARAMS":
                        try:
                            return ast.literal_eval(node.value)
                        except (ValueError, TypeError):
                            # HYPERPARAMS built with expressions (e.g. 2 ** 8),
                            # or JSON-style literals in a hand-written /
                            # LLM-authored candidate: evaluate the restricted
                            # expression instead. Our own templates emit Python
                            # literals (see _render_hyperparams), so this path
                            # only serves foreign candidates.
                            safe_globals = {
                                "__builtins__": {},
                                "true": True, "false": False, "null": None,
                                "True": True, "False": False, "None": None,
                            }
                            return eval(  # noqa: S307 - candidate-internal constants only
                                compile(ast.Expression(node.value), "<hp>", "eval"),
                                safe_globals,
                                {},
                            )
        raise ValueError(f"No HYPERPARAMS assignment found in {program.id}")


# =============================================================================
# GBDT expert (deterministic, no LLM)
# =============================================================================

DEFAULT_GBDT: Dict[str, Any] = {
    "objective": "mse",
    "learning_rate": 0.08,
    "num_leaves": 128,
    "max_depth": 8,
    "colsample_bytree": 0.8,
    "subsample": 0.8,
    "lambda_l1": 100.0,
    "lambda_l2": 500.0,
    "min_data_in_leaf": 50,
    "bagging_freq": 1,
}


class GBDTExpert(ProposalExpert):
    """Deterministic LightGBM config mutation (matches exp2's `mutate` scales).

    Used for explore/mutate/local_hpo actions on the gbdt family. Same
    log-normal perturbation scales as the frozen exp2 pipeline so results
    stay comparable with the measured noise floor.
    """

    model_family = "gbdt"

    #: which hyperparameters belong to which QuantModelSpec component
    _OPTIMIZER_KEYS = {"learning_rate", "lambda_l1", "lambda_l2"}
    _TRAINING_KEYS = {"subsample", "bagging_freq", "min_data_in_leaf"}
    _FEATURE_KEYS = {"colsample_bytree"}

    def build_spec(self, hyperparams: Dict[str, Any]) -> QuantModelSpec:
        hp = dict(hyperparams)
        return QuantModelSpec(
            model_family=self.model_family,
            feature_pipeline={k: hp[k] for k in self._FEATURE_KEYS if k in hp},
            architecture={
                k: v
                for k, v in hp.items()
                if k not in self._OPTIMIZER_KEYS
                and k not in self._TRAINING_KEYS
                and k not in self._FEATURE_KEYS
                and k != "objective"
            },
            loss=str(hp.get("objective", "mse")),
            optimizer={k: hp[k] for k in self._OPTIMIZER_KEYS if k in hp},
            training={k: hp[k] for k in self._TRAINING_KEYS if k in hp},
        )

    def __init__(self, kind: ExpertKind = ExpertKind.MUTATE, rng_seed: int = 0):
        self.kind = kind
        import random

        self._rng = random.Random(rng_seed)

    def propose(
        self,
        action: StructuredAction,
        parents: List[Program],
        *,
        iteration: int,
    ) -> Program:
        base = DEFAULT_GBDT
        if parents:
            try:
                base = self.extract_hyperparams(parents[0])
            except (ValueError, SyntaxError):
                base = dict(DEFAULT_GBDT)

        params = dict(base)
        if self.kind in (ExpertKind.MUTATE, ExpertKind.LOCAL_HPO, ExpertKind.EXPLORE):
            params = self._mutate(params)
        code = _render_template(self.model_family, self.kind.value, params)
        return self._new_program(code, action=action, parents=parents, iteration=iteration)

    def _mutate(self, p: Dict[str, Any]) -> Dict[str, Any]:
        import math

        rng = self._rng
        out = dict(p)
        def lognormal(x, sigma):
            return x * math.exp(rng.gauss(0, sigma))

        out["learning_rate"] = min(0.4, max(0.05, lognormal(float(p["learning_rate"]), 0.20)))
        out["num_leaves"] = int(min(512, max(32, lognormal(float(p["num_leaves"]), 0.25))))
        out["max_depth"] = int(min(12, max(4, p["max_depth"] + rng.randint(-2, 2))))
        out["colsample_bytree"] = min(1.0, max(0.5, p["colsample_bytree"] + rng.gauss(0, 0.06)))
        out["subsample"] = min(1.0, max(0.5, p["subsample"] + rng.gauss(0, 0.06)))
        out["lambda_l1"] = min(800.0, max(20.0, lognormal(float(p["lambda_l1"]), 0.30)))
        out["lambda_l2"] = min(2000.0, max(50.0, lognormal(float(p["lambda_l2"]), 0.30)))
        out["min_data_in_leaf"] = int(min(200, max(5, lognormal(float(p["min_data_in_leaf"]), 0.4))))
        return out


# =============================================================================
# NN expert (LLM-guided, high-variance family)
# =============================================================================

DEFAULT_MLP: Dict[str, Any] = {
    "hidden_dims": [256, 128],
    "dropout": 0.1,
    "learning_rate": 0.001,
    "weight_decay": 0.0001,
    "batch_size": 512,
    "epochs": 20,
    "early_stopping": 5,
    "layer_norm": True,
}


class NNExpert(ProposalExpert):
    """Neural candidate proposer (MLP / temporal blocks).

    Two modes:
    - deterministic config mutation (no LLM, for tests / cheap explore)
    - LLM-guided edit: subclasses or the strategy layer inject
      ``llm_edit_fn(parent_code, action, context_summary) -> new_code``.
      This is the primary path in production; kept as an injectable callable
      so the expert itself stays unit-testable without an LLM.
    """

    model_family = "mlp"

    _OPTIMIZER_KEYS = {"learning_rate", "weight_decay"}
    _TRAINING_KEYS = {"batch_size", "epochs", "early_stopping"}

    def build_spec(self, hyperparams: Dict[str, Any]) -> QuantModelSpec:
        hp = dict(hyperparams)
        return QuantModelSpec(
            model_family=self.model_family,
            feature_pipeline={},
            architecture={
                k: v
                for k, v in hp.items()
                if k not in self._OPTIMIZER_KEYS and k not in self._TRAINING_KEYS
            },
            loss=str(hp.get("loss", "mse")),
            optimizer={k: hp[k] for k in self._OPTIMIZER_KEYS if k in hp},
            training={k: hp[k] for k in self._TRAINING_KEYS if k in hp},
        )

    def __init__(
        self,
        kind: ExpertKind = ExpertKind.EXPLORE,
        rng_seed: int = 0,
        llm_edit_fn: Optional[Any] = None,
        family: str = "mlp",
    ):
        self.kind = kind
        self.model_family = family
        self._llm_edit_fn = llm_edit_fn
        import random

        self._rng = random.Random(rng_seed)

    def propose(
        self,
        action: StructuredAction,
        parents: List[Program],
        *,
        iteration: int,
    ) -> Program:
        if self._llm_edit_fn is not None and parents:
            code = self._llm_edit_fn(parents[0].code, action)
            program = self._new_program(
                code, action=action, parents=parents, iteration=iteration
            )
            program.meta["llm_guided"] = True
            return program

        base = DEFAULT_MLP
        if parents:
            try:
                base = self.extract_hyperparams(parents[0])
            except (ValueError, SyntaxError):
                base = dict(DEFAULT_MLP)
        params = self._mutate(base)
        code = _render_template(self.model_family, self.kind.value, params)
        return self._new_program(code, action=action, parents=parents, iteration=iteration)

    def _mutate(self, p: Dict[str, Any]) -> Dict[str, Any]:
        rng = self._rng
        out = dict(p)
        dims = list(out.get("hidden_dims", [256, 128]))
        # Randomly grow/shrink/shift one layer
        op = rng.choice(["grow", "shrink", "rescale", "toggle_ln"])
        if op == "grow" and len(dims) < 4:
            dims.append(max(32, dims[-1] // 2))
        elif op == "shrink" and len(dims) > 1:
            dims.pop()
        elif op == "rescale":
            idx = rng.randrange(len(dims))
            dims[idx] = int(min(1024, max(32, dims[idx] * rng.choice([0.5, 2.0]))))
        elif op == "toggle_ln":
            out["layer_norm"] = not out.get("layer_norm", True)
        out["hidden_dims"] = dims
        out["dropout"] = min(0.5, max(0.0, out["dropout"] + rng.gauss(0, 0.05)))
        out["learning_rate"] = min(0.01, max(1e-4, out["learning_rate"] * (2 ** rng.gauss(0, 0.5))))
        out["epochs"] = int(min(60, max(5, out["epochs"] + rng.randint(-5, 10))))
        return out


